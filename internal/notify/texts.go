package notify

import "github.com/jlentink/bekup/internal/i18n"

// textFunc formats a text of the package catalog in one language
// (texts.For).
type textFunc func(key string, args ...any) string

// textsFor returns the text function of l.
func textsFor(l i18n.Locale) textFunc { return textFunc(texts.For(l)) }

// n formats the counted phrase key in its ".one" or ".other" form (the
// English forms keep the "(s)" spelling of the original sentences).
func (t textFunc) n(key string, n int64) string {
	if n == 1 {
		return t(key+".one", n)
	}
	return t(key+".other", n)
}

// Key prefixes of the fixed alert sentences: "account."+kind for a
// security.account kind, "system."+kind for a security.system kind
// (formatted alert sentences live under "alert.", "api." and "risk.").
const (
	accountTextPrefix = "account."
	systemTextPrefix  = "system."
)

// accountMessage returns the fixed sentence of an account kind in t;
// "" for a kind without one.
func accountMessage(t textFunc, kind string) string {
	if _, ok := texts[i18n.EN][accountTextPrefix+kind]; !ok {
		return ""
	}
	return t(accountTextPrefix + kind)
}

// systemMessage returns the fixed sentence of a system kind in l.
func systemMessage(l i18n.Locale, kind string) (string, bool) {
	if _, ok := texts[i18n.EN][systemTextPrefix+kind]; !ok {
		return "", false
	}
	return texts.T(l, systemTextPrefix+kind), true
}

