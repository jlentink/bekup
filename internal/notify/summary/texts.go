// t is the text of key in the period's language.
func (p *summaryPeriod) t(key string, args ...any) string {
	return texts.T(p.locale, key, args...)
}

// plural is key's ".one" form for n == 1, else its ".other" form with n.
func (p *summaryPeriod) plural(n int64, key string) string {
	if n == 1 {
		return p.t(key + ".one")
	}
	return p.t(key+".other", n)
}

// joinAnd joins parts as a list ("a, b and c").
func (p *summaryPeriod) joinAnd(parts []string) string {
	switch len(parts) {
	case 0:
		return ""
	case 1:
		return parts[0]
	}
	return p.t("join.and", strings.Join(parts[:len(parts)-1], ", "), parts[len(parts)-1])
}

// time is a local time of the summary ("Mon 3 Nov 2026, 08:00").
func (p *summaryPeriod) time(t time.Time) string {
	return i18n.FormatTime(p.locale, t.In(p.loc), "Mon 2 Jan 2006, 15:04")
}

// cellTime is a short local time for a table cell ("3 Nov 08:00").
func (p *summaryPeriod) cellTime(t time.Time) string {
	return i18n.FormatTime(p.locale, t.In(p.loc), "2 Jan 15:04")
}

// size is a byte count (storage.FormatSize; a decimal comma in Dutch).
func (p *summaryPeriod) size(n int64) string {
	return i18n.LocalizeDecimal(p.locale, storage.FormatSize(n))
}
