// composeHeader starts every compose file setup writes itself
// (setup-first, `--write-compose`).
const composeHeader = `# GENERATED by ` + "`bekup setup init --write-compose`" + ` (D-203, D-205). DO NOT EDIT:
# ` + "`bekup setup upgrade --write-compose`" + ` rewrites this file and refuses (or, with
# --force, backs up) local edits. Put local changes into compose.override.yaml,
# which docker compose merges automatically. Compose variables live in .env.
#
`

// composeSource is the repository compose file embedded in the binary: the
// source of every variant. The deployment file is always ComposeFile.
const composeSource = "docker-compose.yml"

// RenderGenerated renders the compose file setup-first writes: the variant
// (with its database mode) with the image (digest-pinned, or a followed tag
// of the official repository, D-212) behind the "GENERATED" header.
func RenderGenerated(fsys fs.FS, v Variant, db DBMode, img imageref.Ref) ([]byte, error) {
	if _, err := imageref.ParseBekup(img.String()); err != nil {
		return nil, err
	}
	out, err := renderEmbedded(fsys, v, db, &img)
	if err != nil {
		return nil, err
	}
	return append([]byte(composeHeader), out...), nil
}

// RenderRelease renders a variant as published (compose-first): the
// overlay on the embedded compose file with the image line pinned (the
// release assets), or with img nil the ComposePlaceholderLine (the
// committed files in deploy/compose/, written by `just gen`).
func RenderRelease(v Variant, db DBMode, img *imageref.Ref) ([]byte, error) {
	return renderEmbedded(bekup.Assets(), v, db, img)
}

func renderEmbedded(fsys fs.FS, v Variant, db DBMode, img *imageref.Ref) ([]byte, error) {
	src, err := fs.ReadFile(fsys, composeSource)
	if err != nil {
		return nil, fmt.Errorf("reading the embedded compose file: %w", err)
	}
	return RenderVariant(src, v, db, img)
}

// assetFiles lists the embedded deploy/** files below dirs (slash paths).
func assetFiles(fsys fs.FS, dirs []string) ([]string, error) {
	var out []string
	for _, root := range dirs {
		err := fs.WalkDir(fsys, root, func(p string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.Type().IsRegular() {
				out = append(out, p)
			} else if !d.IsDir() {
				return fmt.Errorf("embedded asset %s is not a regular file", p)
			}
			return nil
		})
		if err != nil {
			return nil, fmt.Errorf("listing embedded assets: %w", err)
		}
	}
	sort.Strings(out)
	return out, nil
}

// generatedFiles renders every generated-upgradable file except the state
// file: deploy/** for the variant, reference/* and, setup-first
// (withCompose), the compose file.
func generatedFiles(fsys fs.FS, img imageref.Ref, v Variant, db DBMode, withCompose bool) (map[string][]byte, error) {
	files := map[string][]byte{}
	if withCompose {
		compose, err := RenderGenerated(fsys, v, db, img)
		if err != nil {
			return nil, err
		}
		files[ComposeFile] = compose
	}
	assets, err := assetFiles(fsys, v.assetDirs(db))
	if err != nil {
		return nil, err
	}
	for _, a := range assets {
		b, err := fs.ReadFile(fsys, a)
		if err != nil {
			return nil, err
		}
		files[a] = b
	}
	for dst, src := range referenceFiles {
		b, err := fs.ReadFile(fsys, src)
		if err != nil {
			return nil, err
		}
		files[dst] = b
	}
	return files, nil
}

func quoteTOML(s string) string { return strconv.Quote(s) }

func quoteTOMLList(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = quoteTOML(s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

// renderBekupTOML writes a minimal bekup.toml: only what the deployment
// decides; every other key keeps its built-in default.
func renderBekupTOML(a *Answers) []byte {
	var b bytes.Buffer
	b.WriteString(`# bekup.toml for serve, migrate and admin: written once by ` + "`bekup setup init`" + `
# (D-203). Operator file: edit it freely; ` + "`bekup setup upgrade`" + ` never rewrites
# it, it only re-validates it. Keys that are not set keep their built-in
# defaults, so safer defaults of new releases apply automatically.
# reference/bekup.example.toml documents every key. Check changes with
# ` + "`bekup setup check`" + `. No secrets belong here (only *_file paths).

[server]
`)
	switch {
	case a.ownProxyJoin():
		fmt.Fprintf(&b, "# serve joins your proxy's network %s, where Docker assigns its address, so it\n", a.ProxyNetwork)
		b.WriteString("# binds every interface of its container (D-215; no port is published). In the\n")
		b.WriteString("# own-proxy compose shape (BEKUP_LISTEN_SHAPE) it accepts connections only on\n")
		b.WriteString("# its own address on your proxy's network (the alias bekup-serve) and on\n")
		b.WriteString("# loopback, and keeps the wildcard warning quiet for exactly this address.\n")
	case a.Proxy == ProxyExternal:
		fmt.Fprintf(&b, "# serve binds only its fixed address on the %s link network (SERVE_PROXY_IP).\n", a.Link.Name)
	default:
		b.WriteString("# serve binds only its fixed address on the frontend network.\n")
	}
	fmt.Fprintf(&b, "listen = %s\n", quoteTOML(a.serveListen()))
	if a.ownProxyJoin() {
		b.WriteString("allow_wildcard_listen = true\n")
	}
	fmt.Fprintf(&b, "base_url = %s\n", quoteTOML("https://"+a.Domain))
	switch {
	case a.Proxy == ProxyNone:
		b.WriteString("# Your own reverse proxy on the frontend network (no bundled proxy).\n")
	case a.ownProxyJoin():
		b.WriteString("# Your reverse proxy by its container name: serve resolves it through Docker's\n")
		b.WriteString("# DNS (re-resolved regularly) and trusts exactly its address on that network\n")
		b.WriteString("# (D-215). No CIDRs.\n")
	case a.Proxy == ProxyExternal:
		b.WriteString("# Exactly your reverse proxy's fixed address on the link network (/32, D-205).\n")
	default:
		fmt.Fprintf(&b, "# The bundled %s proxy (PROXY_FRONTEND_IP).\n", a.Proxy)
	}
	fmt.Fprintf(&b, "trusted_proxies = %s\n", quoteTOMLList(a.trustedProxies()))
	if hosts := a.trustedProxyHosts(); len(hosts) > 0 {
		fmt.Fprintf(&b, "trusted_proxy_hosts = %s\n", quoteTOMLList(hosts))
	}
	b.WriteString("\n[metrics]\n# Internal metrics network only (SERVE_METRICS_IP); never published.\n")
	fmt.Fprintf(&b, "listen = %s\n", quoteTOML(a.Network.ServeMetricsIP+":9464"))
	if a.DB.External() {
		b.WriteString(renderDatabaseTOML(&a.DB))
	}
	return b.Bytes()
}

// renderRunnerTOML writes a minimal runner.toml.
func renderRunnerTOML(a *Answers) []byte {
	var b bytes.Buffer
	b.WriteString(`# runner.toml for the runner: written once by ` + "`bekup setup init`" + ` (D-203).
# Operator file: edit it freely; ` + "`bekup setup upgrade`" + ` never rewrites it, it
# only re-validates it. Keys that are not set keep their built-in defaults;
# reference/runner.example.toml documents every key (docs/security/target-allowlist.md).

[listen]
# Only the runner-ctl network address (RUNNER_CTL_IP).
`)
	fmt.Fprintf(&b, "address = %s\n", quoteTOML(a.Network.RunnerCtlIP+":7443"))
	b.WriteString("\n[docker]\n# Group of the Docker socket on the host; must equal DOCKER_GID in .env.\n")
	fmt.Fprintf(&b, "gid = %d\n", a.DockerGID)
	b.WriteString("\n[targets]\n# The databases the runner may reach. Empty = none (deny all).\n")
	fmt.Fprintf(&b, "allow_cidrs = %s\n", quoteTOMLList(nonNil(a.TargetCIDRs)))
	fmt.Fprintf(&b, "allow_hosts = %s\n", quoteTOMLList(nonNil(a.TargetHosts)))
	return b.Bytes()
}

func nonNil(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}

// EnvVar is one KEY=value line of .env.
type EnvVar struct{ Key, Value string }

// envVars returns the .env variables in file order. Values come only from
// validated answers (no quotes, `$`, `#`, spaces or line breaks).
func envVars(a *Answers, version string) []EnvVar {
	var vs []EnvVar
	if a.ImageInEnv {
		vs = append(vs, EnvVar{ImageEnvVar, a.Image.String()})
	}
	vs = append(vs, deploymentEnv(version, imageModeOf(a.Image))...)
	if a.Variant == VariantFull {
		// Only the full variant selects its proxy with a profile.
		profiles := ""
		if a.Proxy != ProxyNone {
			profiles = string(a.Proxy)
		}
		vs = append(vs, EnvVar{"COMPOSE_PROFILES", profiles})
	}
	vs = append(vs, EnvVar{"BEKUP_DOMAIN", a.Domain})
	if a.bundledProxy() {
		vs = append(vs, EnvVar{"PROXY_TLS_MODE", string(a.TLSMode)})
		if a.TLSMode == TLSACME {
			vs = append(vs, EnvVar{"ACME_EMAIL", a.ACMEEmail}, EnvVar{"ACME_CA_SERVER", a.acmeCA()})
		}
	}
	if a.ProxyLabels {
		vs = append(vs, EnvVar{"TRAEFIK_ENTRYPOINT", a.TraefikEntrypoint}, EnvVar{"TRAEFIK_CERTRESOLVER", a.TraefikCertResolver})
	}
	switch {
	case a.ownProxyJoin():
		vs = append(vs, EnvVar{"BEKUP_PROXY_NETWORK", a.ProxyNetwork})
	case a.Proxy == ProxyExternal:
		vs = append(vs, EnvVar{"BEKUP_PROXY_NETWORK", a.Link.Name}, EnvVar{"SERVE_PROXY_IP", a.Link.ServeIP})
	}
	if a.DB.External() && a.DB.Location == DBDocker {
		vs = append(vs, EnvVar{"BEKUP_DB_NETWORK", a.DB.Network})
	}
	vs = append(vs, EnvVar{"DOCKER_GID", strconv.Itoa(a.DockerGID)}, EnvVar{"BEKUP_KEYS_DIR", "./" + a.KeysDir})
	def := DefaultNetwork()
	dv := def.vars()
	n := a.Network
	for i, v := range n.vars() {
		if a.Proxy == ProxyExternal && frontendVar(v.name) {
			continue // no frontend network in the own-proxy variant
		}
		if *v.val != *dv[i].val {
			vs = append(vs, EnvVar{v.name, *v.val})
		}
	}
	return vs
}

// frontendVar reports the compose variables of the frontend network.
func frontendVar(name string) bool {
	return name == "FRONTEND_SUBNET" || name == "SERVE_FRONTEND_IP" || name == "PROXY_FRONTEND_IP"
}

// validEnvValue reports a value .env carries as written (parseDotEnv and
// docker compose read the same text).
func validEnvValue(v string) bool {
	_, bad := parseDotEnv([]byte("X=" + v + "\n"))
	return len(bad) == 0
}

// deploymentEnv are the .env lines setup keeps current on every init and
// upgrade (D-212): BEKUP_SETUP_VERSION, which migrate, serve, worker and runner
// compare with their own version, and BEKUP_IMAGE_MODE=following when
// the image follows a tag (an empty value removes the line).
func deploymentEnv(version string, mode ImageMode) []EnvVar {
	return []EnvVar{
		{deployguard.EnvSetupVersion, strings.TrimPrefix(version, "v")},
		{deployguard.EnvImageMode, string(mode)},
	}
}

// setEnvImageLine is setEnvLine for BEKUP_IMAGE.
func setEnvImageLine(data []byte, value string) ([]byte, error) {
	return setEnvLine(data, ImageEnvVar, value)
}

// setEnvLine returns .env with the key=... line set to value (the first
// one replaced, further ones dropped; appended when missing) or, with
// value "", removed. Every other line stays byte-identical.
func setEnvLine(data []byte, key, value string) ([]byte, error) {
	if value != "" && !validEnvValue(value) {
		return nil, fmt.Errorf("%s: %s cannot be written as a plain value", EnvFile, key)
	}
	lines := strings.SplitAfter(string(data), "\n")
	var b strings.Builder
	done := value == ""
	for _, l := range lines {
		if l == "" {
			continue
		}
		k, _, ok := strings.Cut(strings.TrimSpace(l), "=")
		if ok && k == key {
			if !done {
				fmt.Fprintf(&b, "%s=%s\n", key, value)
				done = true
			}
			continue
		}
		b.WriteString(l)
	}
	if !done {
		if b.Len() > 0 && !strings.HasSuffix(b.String(), "\n") {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "%s=%s\n", key, value)
	}
	return []byte(b.String()), nil
}

// syncEnvImage keeps the BEKUP_IMAGE line of .env in step with the
// compose mode (D-205 amendment 3): img (non-empty) when compose.yaml
// takes the image from BEKUP_IMAGE, no line otherwise. It writes .env
// only when the content changes and reports whether it did.
func syncEnvImage(w *writer, img string) (bool, error) {
	return syncEnv(w, []EnvVar{{ImageEnvVar, img}})
}

// syncEnv sets (or, with an empty value, removes) the lines of vars in
// .env, creating it when a value is to be written. It writes .env only
// when the content changes and reports whether it did.
func syncEnv(w *writer, vars []EnvVar) (bool, error) {
	cur, next, err := envWithLines(w.root, vars)
	if err != nil || bytes.Equal(next, cur) {
		return false, err
	}
	return true, w.replace(EnvFile, next, 0o644)
}

// envWithLines returns the current .env (nil when missing) and the
// content with the lines of vars set or removed (nil when it neither
// exists nor gains a line).
func envWithLines(root string, vars []EnvVar) (cur, next []byte, err error) {
	cur, err = readManaged(root, EnvFile)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		cur = nil
	case err != nil:
		return nil, nil, err
	}
	next = cur
	for _, v := range vars {
		if next == nil && v.Value == "" {
			continue
		}
		if next, err = setEnvLine(next, v.Key, v.Value); err != nil {
			return nil, nil, err
		}
	}
	return cur, next, nil
}

func renderEnv(a *Answers, version string) []byte {
	var b bytes.Buffer
	b.WriteString(`# Compose variables, written once by ` + "`bekup setup init`" + ` (D-203). Operator
# file: ` + "`bekup setup upgrade`" + ` only updates the BEKUP_SETUP_VERSION,
# BEKUP_IMAGE_MODE (and, with the committed compose file, BEKUP_IMAGE) lines.
# No secrets belong here.
# A variable set in the shell that runs docker compose overrides this file;
# keep them unset. Changing BEKUP_DOMAIN or an address here also needs the
# matching change in bekup.toml / runner.toml (` + "`bekup setup check`" + `).
# BEKUP_SETUP_VERSION is the version setup prepared this directory for:
# migrate, serve, worker and runner refuse to start with another version (D-212).
`)
	for _, v := range envVars(a, version) {
		if v.Value == "" && v.Key == deployguard.EnvImageMode {
			continue // pinned: no line (setEnvLine semantics)
		}
		fmt.Fprintf(&b, "%s=%s\n", v.Key, v.Value)
	}
	return b.Bytes()
}

// renderOverride writes compose.override.yaml: the setup-only overlays
// (D-215: Traefik labels, link network, database container network) and,
// for PROXY_TLS_MODE=static, the operator's certificate directory at
// /certs (and no certbot).
func renderOverride(a *Answers) []byte {
	static := Proxy("")
	if a.bundledProxy() && a.TLSMode == TLSStatic {
		static = a.Proxy
	}
	doc := overlayDoc(a.overlays(), static)
	if doc == "" {
		return nil
	}
	return []byte(overlayHeader + doc)
}

// operatorFiles renders the operator-class files for the answers.
func operatorFiles(a *Answers, version string) map[string][]byte {
	files := map[string][]byte{
		EnvFile:    renderEnv(a, version),
		BekupTOML:  renderBekupTOML(a),
		RunnerTOML: renderRunnerTOML(a),
	}
	if o := renderOverride(a); o != nil {
		files[OverrideFile] = o
	}
	return files
}

// isAssetPath reports whether p is a path setup may manage as a generated
// asset (used to validate state files).
func isAssetPath(p string) bool {
	if p == ComposeFile {
		return true
	}
	if _, ok := referenceFiles[p]; ok {
		return true
	}
	if path.Clean(p) != p || strings.Contains(p, "..") {
		return false
	}
	for _, d := range assetDirs {
		if strings.HasPrefix(p, d+"/") {
			return true
		}
	}
	return false
}
