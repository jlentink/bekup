/**
 * The job's encryption status and, for admins, the key actions (D-142,
 * D-154). Every action needs a fresh step-up; generated keys are shown
 * once and never kept in the Apollo cache (no-cache mutations).
 */
export function EncryptionPanel({ job, admin }: { job: Job; admin: boolean }) {
  const enc = job.encryption;
  const { withStepUp } = useStepUp();
  const refetch = { refetchQueries: [JobDetailQuery], awaitRefetchQueries: true };
  const [genPassphrase] = useMutation(GenerateJobPassphraseMutation, {
    fetchPolicy: "no-cache",
    ...refetch,
  });
  const [setPassphrase] = useMutation(SetJobPassphraseMutation, refetch);
  const [genKeypair] = useMutation(GenerateAgeKeypairMutation, {
    fetchPolicy: "no-cache",
    ...refetch,
  });
  const [setRecipient] = useMutation(SetJobRecipientMutation, refetch);
  const [optIn] = useMutation(EnableJobEncryptionMutation, refetch);
  const [optOut] = useMutation(DisableJobEncryptionMutation, refetch);
  const [exportPassphrases] = useMutation(ExportJobPassphrasesMutation, {
    fetchPolicy: "no-cache",
  });

  const [dialog, setDialog] = useState<
    null | "generate" | "passphrase" | "keypair" | "recipient" | "optOut" | "export"
  >(null);
  const [shown, setShown] = useState<OneTimeKey | null>(null);
  const close = () => {
    setDialog(null);
  };
  /** Runs a key action with step-up; errors go to the caller (dialogs show them inline). */
  const run = async (op: () => Promise<unknown>) => {
    await withStepUp(op);
    toast.success(T.changed);
  };

  return (
    <div className="flex flex-col gap-4">
      <div className="flex flex-wrap items-center gap-3">
        <EncryptionBadge encryption={enc} />
        {enc.optedOut && enc.optedOutAt ? (
          <span className="text-xs text-status-insecure-fg">
            {T.optedOut(formatDateTime(enc.optedOutAt))}
          </span>
        ) : null}
      </div>
      <dl className="grid grid-cols-[max-content_minmax(0,1fr)] gap-x-6 gap-y-1.5 text-sm">
        {enc.optedOut && enc.optOutReason ? (
          <>
            <dt className="text-muted-foreground">{T.reason}</dt>
            <dd className="text-status-insecure-fg">{enc.optOutReason}</dd>
          </>
        ) : null}
        {enc.passphrase ? (
          <>
            <dt className="text-muted-foreground">{T.passphraseVersion}</dt>
            <dd className="font-mono text-xs">
              v{enc.passphrase.version} · {formatDateTime(enc.passphrase.createdAt)}
              {enc.mode === "PASSPHRASE" ? "" : " (inactive)"}
            </dd>
          </>
        ) : null}
        {enc.recipient ? (
          <>
            <dt className="text-muted-foreground">{T.recipient}</dt>
            <dd className="font-mono text-xs break-all">
              v{enc.recipient.version} · {enc.recipient.recipient}
              {enc.recipient.label ? ` · ${enc.recipient.label}` : ""}
              {enc.mode === "RECIPIENT" ? "" : " (inactive)"}
              {enc.recipient.generated ? (
                <span className="block text-muted-foreground">{T.generatedNote}</span>
              ) : null}
            </dd>
            <dt className="text-muted-foreground">{T.fingerprint}</dt>
            <dd className="font-mono text-2xs break-all text-muted-foreground">
              {enc.recipient.fingerprint}
            </dd>
          </>
        ) : null}
      </dl>

      {admin ? (
        <div role="group" aria-label={T.actions} className="flex flex-wrap gap-2">
          <ActionButton
            icon={Sparkles}
            onClick={() => {
              setDialog("generate");
            }}
          >
            {T.generatePassphrase}
          </ActionButton>
          <ActionButton
            icon={KeyRound}
            onClick={() => {
              setDialog("passphrase");
            }}
          >
            {T.setPassphrase}
          </ActionButton>
          <ActionButton
            icon={FileKey2}
            onClick={() => {
              setDialog("keypair");
            }}
          >
            {T.generateKeypair}
          </ActionButton>
          <ActionButton
            icon={LockKeyhole}
            onClick={() => {
              setDialog("recipient");
            }}
          >
            {T.setRecipient}
          </ActionButton>
          {enc.passphrase ? (
            <ActionButton
              icon={FileKey2}
              onClick={() => {
                setDialog("export");
              }}
            >
              {T.export}
            </ActionButton>
          ) : null}
          {enc.optedOut ? (
            (["PASSPHRASE", "RECIPIENT"] as const)
              .filter((m) => (m === "PASSPHRASE" ? enc.passphrase : enc.recipient))
              .map((m) => (
                <ActionButton
                  key={m}
                  icon={ShieldPlus}
                  onClick={() => {
                    run(() => optIn({ variables: { jobId: job.id, mode: m } })).catch(
                      reportActionError,
                    );
                  }}
                >
                  {T.optIn(m === "PASSPHRASE" ? "passphrase" : "recipient")}
                </ActionButton>
              ))
          ) : (
            <Button
              variant="outline"
              size="sm"
              className="border-status-insecure/50 text-status-insecure-fg hover:bg-status-insecure-soft"
              onClick={() => {
                setDialog("optOut");
              }}
            >
              <ShieldOff aria-hidden="true" /> {T.optOut}
            </Button>
          )}
        </div>
      ) : (
        <p className="text-xs text-muted-foreground">{T.adminOnly}</p>
      )}

      <ConfirmDialog
        open={dialog === "generate"}
        onOpenChange={(o) => {
          if (!o) close();
        }}
        title={T.generateTitle}
        description={T.generateLead}
        confirmLabel={T.generatePassphrase}
        onConfirm={async () => {
          try {
            const r = await withStepUp(() => genPassphrase({ variables: { jobId: job.id } }));
            const g = r.data?.generateJobPassphrase;
            if (g) setShown(passphraseKey(job.slug, g.passphrase, g.version));
          } catch (err) {
            reportActionError(err);
            throw err;
          }
        }}
      />
      <ConfirmDialog
        open={dialog === "export"}
        onOpenChange={(o) => {
          if (!o) close();
        }}
        title={T.exportTitle}
        description={T.exportLead}
        confirmLabel={T.export}
        destructive
        onConfirm={async () => {
          try {
            const r = await withStepUp(() => exportPassphrases({ variables: { jobId: job.id } }));
            const e = r.data?.exportJobPassphrases;
            if (e) {
              downloadText(e.fileName, e.content);
              toast.success(T.exported);
            }
          } catch (err) {
            reportActionError(err);
            throw err;
          }
        }}
      />
      <SetPassphraseDialog
        open={dialog === "passphrase"}
        onClose={close}
        onSubmit={(passphrase) =>
          run(() => setPassphrase({ variables: { jobId: job.id, passphrase } }))
        }
      />
      <TextActionDialog
        open={dialog === "keypair"}
        onClose={close}
        title={T.keypairTitle}
        lead={T.keypairLead}
        submitLabel={T.generateKeypair}
        fields={[{ name: "label", label: T.label, hint: T.labelHint, optional: true }]}
        onSubmit={async ({ label }) => {
          const r = await withStepUp(() =>
            genKeypair({ variables: { jobId: job.id, ...(label ? { label } : {}) } }),
          );
          const k = r.data?.generateAgeKeypair;
          if (k) setShown(identityKey(k));
        }}
      />
      <TextActionDialog
        open={dialog === "recipient"}
        onClose={close}
        title={T.recipientTitle}
        lead={T.recipientLead}
        submitLabel={T.setRecipient}
        fields={[
          {
            name: "recipient",
            label: T.recipientField,
            mono: true,
            validate: (v) => (AGE_RECIPIENT_RE.test(v.trim()) ? null : T.recipientInvalid),
          },
          { name: "label", label: T.label, hint: T.labelHint, optional: true },
        ]}
        onSubmit={({ recipient, label }) =>
          run(() =>
            setRecipient({
              variables: {
                jobId: job.id,
                recipient: (recipient ?? "").trim(),
                ...(label ? { label } : {}),
              },
            }),
          )
        }
      />
      <OptOutDialog
        open={dialog === "optOut"}
        onClose={close}
        onSubmit={(reason) => run(() => optOut({ variables: { jobId: job.id, reason } }))}
      />
      <OneTimeKeyDialog
        value={shown}
        onDone={() => {
          setShown(null);
        }}
      />
    </div>
  );
}

function ActionButton({
  icon: Icon,
  onClick,
  children,
}: {
  icon: typeof KeyRound;
  onClick: () => void;
  children: ReactNode;
}) {
  return (
    <Button variant="outline" size="sm" onClick={onClick}>
      <Icon aria-hidden="true" /> {children}
    </Button>
  );
}

/** Shared frame of the small key dialogs: busy state, error line, footer. */
function ActionDialog({
  open,
  onClose,
  title,
  lead,
  submitLabel,
  destructive = false,
  canSubmit,
  onSubmit,
  children,
  className,
}: {
  open: boolean;
  onClose: () => void;
  title: string;
  lead: ReactNode;
  submitLabel: string;
  destructive?: boolean;
  canSubmit: boolean;
  onSubmit: () => Promise<void>;
  children: ReactNode;
  className?: string;
}) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  return (
    <Dialog
      open={open}
      onOpenChange={(o) => {
        if (!o && !busy) {
          setError(null);
          onClose();
        }
      }}
    >
      <DialogContent className={cn("gap-5 sm:max-w-lg", className)}>
        <form
          className="flex flex-col gap-5"
          noValidate
          onSubmit={(e) => {
            e.preventDefault();
            if (!canSubmit || busy) return;
            setBusy(true);
            setError(null);
            onSubmit()
              .then(() => {
                onClose();
              })
              .catch((err: unknown) => {
                if (!isStepUpCancelled(err)) setError(userMessage(err));
              })
              .finally(() => {
                setBusy(false);
              });
          }}
        >
          <DialogHeader>
            <DialogTitle>{title}</DialogTitle>
            <DialogDescription>{lead}</DialogDescription>
          </DialogHeader>
          {children}
          {error ? (
            <p role="alert" className="text-sm text-destructive">
              {error}
            </p>
          ) : null}
          <DialogFooter>
            <Button type="button" variant="outline" disabled={busy} onClick={onClose}>
              {T.cancel}
            </Button>
            <Button
              type="submit"
              variant={destructive ? "destructive" : "default"}
              disabled={!canSubmit || busy}
            >
              {submitLabel}
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  );
}

function SetPassphraseDialog({
  open,
  onClose,
  onSubmit,
}: {
  open: boolean;
  onClose: () => void;
  onSubmit: (passphrase: string) => Promise<void>;
}) {
  const [pw, setPw] = useState("");
  const [repeat, setRepeat] = useState("");
  const meterId = useId();
  const deferred = useDeferredValue(pw);
  const estimate = useMemo(
    () => (deferred ? estimateStrength(deferred, [], MIN_JOB_PASSPHRASE) : null),
    [deferred],
  );
  const length = Array.from(pw).length;
  const problem =
    pw === ""
      ? null
      : length < MIN_JOB_PASSPHRASE
        ? T.tooShort
        : (estimate?.score ?? 0) < MIN_ACCEPTED_SCORE + 1
          ? T.weak
          : null;
  const mismatch = repeat !== "" && repeat !== pw ? T.mismatch : null;
  const reset = () => {
    setPw("");
    setRepeat("");
    onClose();
  };
  return (
    <ActionDialog
      open={open}
      onClose={reset}
      title={T.setPassphraseTitle}
      lead={T.setPassphraseLead}
      submitLabel={T.setPassphrase}
      canSubmit={pw !== "" && problem === null && repeat === pw}
      onSubmit={() => onSubmit(pw)}
    >
      <Field label={T.passphrase} error={problem}>
        {({ id, describedBy, invalid }) => (
          <>
            <Input
              id={id}
              type="password"
              autoComplete="new-password"
              aria-describedby={[describedBy, meterId].filter(Boolean).join(" ")}
              aria-invalid={invalid}
              value={pw}
              onChange={(e) => {
                setPw(e.target.value);
              }}
            />
            <StrengthMeter estimate={estimate} id={meterId} />
          </>
        )}
      </Field>
      <Field label={T.repeat} error={mismatch}>
        {({ id, describedBy, invalid }) => (
          <Input
            id={id}
            type="password"
            autoComplete="new-password"
            aria-describedby={describedBy}
            aria-invalid={invalid}
            value={repeat}
            onChange={(e) => {
              setRepeat(e.target.value);
            }}
          />
        )}
      </Field>
    </ActionDialog>
  );
}

interface TextField {
  name: string;
  label: string;
  hint?: string;
  optional?: boolean;
  mono?: boolean;
  validate?: (value: string) => string | null;
}

function TextActionDialog({
  open,
  onClose,
  title,
  lead,
  submitLabel,
  fields,
  onSubmit,
}: {
  open: boolean;
  onClose: () => void;
  title: string;
  lead: string;
  submitLabel: string;
  fields: TextField[];
  onSubmit: (values: Record<string, string | undefined>) => Promise<void>;
}) {
  const [values, setValues] = useState<Record<string, string>>({});
  const errors = Object.fromEntries(
    fields.map((f) => {
      const v = values[f.name] ?? "";
      return [f.name, v === "" ? null : (f.validate?.(v) ?? null)];
    }),
  );
  const canSubmit = fields.every(
    (f) => (f.optional === true || (values[f.name] ?? "").trim() !== "") && !errors[f.name],
  );
  const reset = () => {
    setValues({});
    onClose();
  };
  return (
    <ActionDialog
      open={open}
      onClose={reset}
      title={title}
      lead={lead}
      submitLabel={submitLabel}
      canSubmit={canSubmit}
      onSubmit={() =>
        onSubmit(
          Object.fromEntries(
            fields.map((f) => [f.name, (values[f.name] ?? "").trim() || undefined]),
          ),
        )
      }
    >
      {fields.map((f) => (
        <Field key={f.name} label={f.label} hint={f.hint} error={errors[f.name]}>
          {({ id, describedBy, invalid }) => (
            <Input
              id={id}
              aria-describedby={describedBy}
              aria-invalid={invalid}
              spellCheck={false}
              autoComplete="off"
              value={values[f.name] ?? ""}
              onChange={(e) => {
                setValues((s) => ({ ...s, [f.name]: e.target.value }));
              }}
              className={f.mono ? "font-mono text-xs" : undefined}
            />
          )}
        </Field>
      ))}
    </ActionDialog>
  );
}

function OptOutDialog({
  open,
  onClose,
  onSubmit,
}: {
  open: boolean;
  onClose: () => void;
  onSubmit: (reason: string) => Promise<void>;
}) {
  const [reason, setReason] = useState("");
  const [ack, setAck] = useState(false);
  const reset = () => {
    setReason("");
    setAck(false);
    onClose();
  };
  return (
    <ActionDialog
      open={open}
      onClose={reset}
      title={T.optOutTitle}
      lead={T.optOutLead}
      submitLabel={T.optOutConfirm}
      destructive
      canSubmit={reason.trim() !== "" && ack}
      onSubmit={() => onSubmit(reason.trim())}
      className="border-status-insecure/60"
    >
      <div
        aria-hidden="true"
        className="hatch-insecure -mt-2 h-2 rounded-sm border border-status-insecure/60"
      />
      <Field label={T.optOutReason}>
        {({ id }) => (
          <textarea
            id={id}
            required
            rows={3}
            maxLength={500}
            value={reason}
            onChange={(e) => {
              setReason(e.target.value);
            }}
            className="w-full rounded-md border border-input bg-surface px-3 py-2 text-sm shadow-xs outline-none focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/50 dark:bg-surface-sunken"
          />
        )}
      </Field>
      <CheckboxField
        label={T.optOutAck}
        checked={ack}
        onChange={(e) => {
          setAck(e.target.checked);
        }}
      />
    </ActionDialog>
  );
}
