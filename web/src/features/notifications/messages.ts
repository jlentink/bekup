function ordinal(n: number): string {
  const tens = n % 100;
  if (tens >= 11 && tens <= 13) return `${String(n)}th`;
  const suffix = ["th", "st", "nd", "rd"][n % 10] ?? "th";
  return `${String(n)}${suffix}`;
}

